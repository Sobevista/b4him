def test_referee_W3_a_merge_commit_above_the_release_does_not_ride(site):
    root, bare, origin_head, commit = stranded(site)
    # a side branch from the pre-release head carrying a page, merged above the release
    g(root, "branch", "side", origin_head)
    g(root, "checkout", "-q", "side")
    commit_files(root, "side page", **{"lessons/evil/index.html": "<p>evil</p>\n"})
    g(root, "checkout", "-q", "main")
    g(root, "merge", "-q", "--no-ff", "-m", "merge side", "side")
    assert len(g(root, "rev-list", "--parents", "-n", "1", "HEAD").split()) == 3
    refused_and_origin_still(bare, origin_head, commit)
    assert "evil" not in g(bare, "ls-tree", "-r", "--name-only", "main")
    # a merge whose side branch is bookkeeping-only is still a merge: never provably the release or bookkeeping
    g(root, "reset", "-q", "--hard", commit)
    g(root, "branch", "-f", "side2", origin_head)
    g(root, "checkout", "-q", "side2")
    commit_files(root, "side bookkeeping", **{"boards/APPROVALS_OWED.md": "# owed, by side\n"})
    g(root, "checkout", "-q", "main")
    g(root, "merge", "-q", "--no-ff", "-m", "merge side2", "side2")
    refused_and_origin_still(bare, origin_head, commit)
    # hand-built merge objects whose tree smuggles a page: two identical parents; parents (release, pre-release head)
    for parents in ([commit, commit], [commit, origin_head], [origin_head, commit]):
        g(root, "reset", "-q", "--hard", commit)
        plumb_commit(root, commit, {"lessons/evil/index.html": "<p>evil</p>\n"}, parents=parents, msg="hand-built merge")
        refused_and_origin_still(bare, origin_head, commit)
        assert "evil" not in g(bare, "ls-tree", "-r", "--name-only", "main")


