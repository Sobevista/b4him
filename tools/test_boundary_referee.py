def commit_files(root, msg, **files):
    for rel, text in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")
        g(root, "add", "--", rel)
    g(root, "commit", "-q", "-m", msg)
    return g(root, "rev-parse", "HEAD")


def plumb_commit(root, parent, files: dict, parents=None, msg="plumbed") -> str:
    """A commit built with git plumbing on top of `parent`'s tree: exact paths (case preserved, no checkout), any
    parents. Moves main to it and resets the tree."""
    with tempfile.TemporaryDirectory() as td:
        env = {**os.environ, "GIT_INDEX_FILE": os.path.join(td, "idx")}

        def run(*a):
            p = subprocess.run([GIT, "-C", str(root), *a], env=env, capture_output=True, encoding="utf-8")
            assert p.returncode == 0, (a, p.stderr)
            return p.stdout.strip()
        run("read-tree", parent)
        for rel, text in files.items():
            f = pathlib.Path(td) / "f"
            f.write_text(text, encoding="utf-8", newline="\n")
            blob = run("hash-object", "-w", str(f))
            run("update-index", "--add", "--cacheinfo", f"100644,{blob},{rel}")
        tree = run("write-tree")
    args = []
    for p in (parents or [parent]):
        args += ["-p", p]
    c = g(root, "commit-tree", tree, *args, "-m", msg)
    g(root, "update-ref", "refs/heads/main", c)
    g(root, "reset", "-q", "--hard")
    return c


