def test_DEFECT_D4_invisible_characters_hide_a_name_or_split_a_surname(reg):
    """Soft hyphens (&shy;, inserted by some editors on paste), zero-width space/joiners and bidi marks are decoded by
    html.unescape but are not letters, so a name containing one is not the name, and a child's surname after one is
    not a surname. Visually the text is unchanged."""
    missed = []
    for sep in ("&shy;", "&#8203;", "&zwnj;", "&zwj;", "&lrm;", "\u00ad", "\u200b"):
        r = pr.check_text(f"<p>Peregrine{sep}Farquharson helped.</p>", piece_yes={"CHILD-1"}, registry=reg)
        if not any("surname" in f.rule for f in r.findings):
            missed.append(f"child surname behind {sep!r}")
        r = pr.check_text(f"<p>Ott{sep}oline Farquharson signed.</p>", registry=reg)
        if r.ok:
            missed.append(f"client name with {sep!r} inside")
    assert not missed, missed


