def test_referee_W1_the_digest_requirement_has_no_bypass(tmp_path):
    real = binding.legacy_exceptions()
    want = real["GC-GLOSS-1"]["approved_digest"]
    assert len(want) == 64 and want == want.lower() and int(want, 16)
    rows = [json.loads(l) for l in (REAL_ROOT / "production_queue.jsonl").read_text(encoding="utf-8").splitlines()
            if l.strip().startswith("{")]
    gloss = next(r for r in rows if r["id"] == "GC-GLOSS-1")
    assert binding.bytes_digest(gloss) == want and binding.problems(gloss) == []
    f = tmp_path / "legacy.json"

    def refused(row, path=f):
        try:
            return bool(binding.problems(row, path))
        except Exception:                 # noqa: BLE001 - a raise is fail-closed, never a cover
            return True
    for bad in (None, "", " ", "\t", [want], {"sha256": want}, 0, 1, True, False, want.upper(), " " + want, want + "\n",
                want[:-1], want + "0", want.encode().hex()):
        f.write_text(json.dumps({"exceptions": [{"id": "GC-GLOSS-1", "approved_digest": bad}]}), encoding="utf-8")
        assert refused(gloss), repr(bad)
    f.write_text(json.dumps({"exceptions": [{"id": "GC-GLOSS-1"}]}), encoding="utf-8")
    assert refused(gloss)
    # the right digest, the wrong row: any change to what would go live breaks it
    f.write_text(json.dumps({"exceptions": [{"id": "GC-GLOSS-1", "approved_digest": want}]}), encoding="utf-8")
    assert not refused(gloss)
    for mutate in (lambda r: r["approved_blobs"].update({"lessons/extra/index.html": "b" * 40}),
                   lambda r: r["approved_blobs"].update({next(iter(r["approved_blobs"])): "c" * 40}),
                   lambda r: r["approved_blobs"].pop(next(iter(r["approved_blobs"]))),
                   lambda r: r.update(approved_index_entry="d" * 64),
                   lambda r: r.update(approved_blobs={k.upper(): v for k, v in r["approved_blobs"].items()}),
                   lambda r: r.update(approved_blobs={k.replace("/", "\\"): v for k, v in r["approved_blobs"].items()}),
                   lambda r: r.update(id="GC-GLOSS-1 "), lambda r: r.update(id=["GC-GLOSS-1"]), lambda r: r.pop("id")):
        m = copy.deepcopy(gloss)
        mutate(m)
        assert refused(m), m.get("id")
    # the pin travels with the data file, not with the row: a digest written INTO the row is ignored
    m = copy.deepcopy(gloss)
    m["approved_blobs"][next(iter(m["approved_blobs"]))] = "c" * 40
    m["approved_digest"] = binding.bytes_digest(m)
    m["legacy_digest"] = binding.bytes_digest(m)
    assert refused(m)


