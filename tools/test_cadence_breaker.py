def test_ATTACK_tuesday_only_across_four_weeks_only_tuesdays_publish(site):
    """Every calendar day Mon 10-19 .. Sun 11-15 with a whole racked piece and nothing published: exactly the
    Tuesdays say PUBLISH, every other day says SKIP as not a release day."""
