def origin(root, tmp_path):
    bare = tmp_path / "origin.git"
    g(tmp_path, "init", "-q", "--bare", "-b", "main", str(bare))
    g(root, "remote", "add", "origin", str(bare))
    g(root, "push", "-q", "origin", "main")
    return bare


# ===================================================================== 1. only the release path can publish
def test_only_the_release_path_can_publish(site, tmp_path, monkeypatch):
    root, write_queue, bound_piece, blob_of = site
    row = bound_piece()
    write_queue(row)
    bare = origin(root, tmp_path)
    head = origin_head = g(root, "rev-parse", "HEAD")
    good = release.plan(TUE)
    assert good["outcome"] == "PUBLISH" and good["piece"] == "P1"        # the honest path is open...

    def nothing_moved():
        assert g(root, "rev-parse", "HEAD") == head and g(root, "status", "--porcelain") == ""
        assert g(bare, "rev-parse", "main") == head

    # -- a call from outside the scheduled entry: refused, with a perfectly good decision in hand
    with pytest.raises(release.ReleaseError, match="outside the scheduled entry"):
        release.apply(TUE, good)
    with pytest.raises(release.ReleaseError, match="outside the scheduled entry"):
        release.push_release(TUE, head)
    nothing_moved()

    # -- a forged decision dict on a Friday (the breaker's case), even from inside an entry opened for that Friday:
    #    the day is re-checked inside apply() itself, and the board gives a Friday no slot
    with release.scheduled_entry(FRI):
        with pytest.raises(release.ReleaseError, match="not re-derived"):
            release.apply(FRI, {"outcome": "PUBLISH", "piece": "P1", "row": row})
    nothing_moved()

    with release.scheduled_entry(TUE):
        # -- the entry was opened for one day only
        with pytest.raises(release.ReleaseError, match="not the day the scheduled entry was opened for"):
            release.apply(NEXT_TUE, {"outcome": "PUBLISH", "piece": "P1", "row": row})
        # -- a forged decision naming another piece, or the right piece with other bytes
        with pytest.raises(release.ReleaseError, match="does not match"):
            release.apply(TUE, {**good, "piece": "SOMEONE-ELSE"})
        swapped = copy.deepcopy(row)
        swapped["approved_blobs"][PAGE] = blob_of(b"<h1>swapped</h1>\n")
        with pytest.raises(release.ReleaseError, match="does not match"):
            release.apply(TUE, {"outcome": "PUBLISH", "piece": "P1", "row": swapped})
        nothing_moved()

        # -- a forged decision past the cap: one piece already published in the 7 days to TUE
        write_queue(row, {"id": "OLD", "order": 9, "title": "o", "stage": "PUBLISHED", "published": "2026-10-14"})
        head = g(root, "rev-parse", "HEAD")
        with pytest.raises(release.ReleaseError, match="cap"):
            release.apply(TUE, {"outcome": "PUBLISH", "piece": "P1", "row": row})
        assert g(root, "rev-parse", "HEAD") == head

        # -- a forged queue row: racked by hand, no v3 binding. Even a decision written to match it is refused.
        forged = {k: v for k, v in bound_piece("P2").items() if k not in ("binding", "approved_commit")}
        write_queue(forged)
        head = g(root, "rev-parse", "HEAD")
        d = release.plan(TUE)
        assert d["outcome"] == "FAIL" and "UNVERIFIED" in d["why"]
        with pytest.raises(release.ReleaseError, match="not re-derived"):
            release.apply(TUE, {"outcome": "PUBLISH", "piece": "P2", "row": forged})
        # -- a forged binding: the marker pasted on, with a digest nobody computed
        forged["binding"] = {"version": 3, "commit": "0" * 40, "digest": "f" * 64}
        forged["approved_commit"] = "0" * 40
        write_queue(forged)
        head = g(root, "rev-parse", "HEAD")
        assert release.plan(TUE)["outcome"] == "FAIL"

        # -- an altered package: a bound row whose pinned bytes were edited in the queue afterwards
        altered = bound_piece("P3")
        altered["approved_blobs"][PAGE] = blob_of(b"<h1>not what he approved</h1>\n")
        write_queue(altered)
        head = g(root, "rev-parse", "HEAD")
        d = release.plan(TUE)
        assert d["outcome"] == "FAIL" and "digest" in d["why"], d
        with pytest.raises(release.ReleaseError):
            release.apply(TUE, {"outcome": "PUBLISH", "piece": "P3", "row": altered})
        # ...and a package altered in the TREE after approval never publishes either
        write_queue(row)
        (root / PAGE).parent.mkdir(parents=True, exist_ok=True)
        (root / PAGE).write_bytes(b"<h1>edited in the tree</h1>\n")
        assert release.plan(TUE)["outcome"] == "SKIP"
        (root / PAGE).unlink()
        (root / PAGE).parent.rmdir()
        head = g(root, "rev-parse", "HEAD")

        # -- push: anything that is not exactly the release commit is refused, and the origin does not move
        (root / "lessons" / "a" / "index.html").write_text("<p>smuggled, never approved</p>\n", encoding="utf-8")
        g(root, "commit", "-q", "-am", "PUBLISHED P1 on its Tue slot: (a lie in the subject)")
        stray = g(root, "rev-parse", "HEAD")
        with pytest.raises(release.ReleaseError, match="unapproved|not provably"):
            release.push_release(TUE, stray)
        assert g(bare, "rev-parse", "main") == origin_head
        g(root, "reset", "-q", "--hard", head)

        # -- the honest release: committed, and only then pushed, by the one function that pushes
        d = release.plan(TUE)
        commit = release.apply(TUE, d)
        release.push_release(TUE, commit)
        assert g(bare, "rev-parse", "main") == commit

    # -- a failed release never falls into a broader push
    root2_calls = []
    real_git = release.git

    def spy(*args, **kw):
        root2_calls.append(args)
        return real_git(*args, **kw)
    monkeypatch.setattr(release, "git", spy)
    bad = blob_of(b'<a href="/lessons/nowhere/">x</a>\n')
    broken = bound_piece("P4", approved_blobs={"lessons/p4/index.html": bad, "tools/tracks/n8n.html": pb.blob_sha(root / "tools/tracks/n8n.html")})
    v3_testkit.bind(broken)
    write_queue(broken)
    entry = {}
    args = type("A", (), {"push": True, "verify_live": False, "live_minutes": 0})()
    with release.scheduled_entry(NEXT_TUE):
        with pytest.raises(release.ReleaseError, match="404"):
            release.run(args, NEXT_TUE, entry)
            pytest.fail(f"expected the broken link to stop the release: {entry}")
    assert not [c for c in root2_calls if c and c[0] == "push"], root2_calls
    assert g(root, "status", "--porcelain") == ""


def test_push_exists_in_one_function_and_the_daily_job_has_no_other_door():
    """Static: of everything under tools/ that is not a test, exactly one place runs `git push`."""
    hits = []
    for p in sorted(HERE.rglob("*")):
        if (p.suffix in (".py", ".cmd", ".ps1", ".bat") and not p.name.startswith("test_") and p.name != "conftest.py"
                and "capability_inventory" not in p.parts):       # the inventory READS for the word; it pushes nothing
            for n, line in enumerate(p.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
                code = line.split("#")[0] if p.suffix == ".py" else line
                if re.search(r"""["']push["']""" if p.suffix == ".py" else r"git\s+push", code):
                    hits.append(f"{p.name}:{n}")
    assert hits == [h for h in hits if h.startswith("release.py:")] and len(hits) == 1, hits
    daily = (HERE / "daily.cmd").read_text(encoding="utf-8")
    assert "release.py --apply --push --verify-live" in daily and "git push" not in daily


# ===================================================================== 2. eligibility at release time
def test_release_refuses_a_piece_without_current_bindings_and_the_legacy_exception_covers_one_piece(site, tmp_path):
    root, write_queue, bound_piece, blob_of = site

    # a bound piece is eligible; the same piece without the marker is UNVERIFIED
    ok = bound_piece("P1")
    assert binding.problems(ok) == []
    bare = {k: v for k, v in ok.items() if k not in ("binding", "approved_commit")}
    assert any("UNVERIFIED" in p for p in binding.problems(bare))
    write_queue(bare)
    d = release.plan(TUE)
    assert d["outcome"] == "FAIL" and "UNVERIFIED" in d["why"]

    # a marker from an older version, a changed byte pin, a missing tag, a commit that does not hold the bytes
    assert any("UNVERIFIED" in p for p in binding.problems({**ok, "binding": {**ok["binding"], "version": 2}}))
    moved = copy.deepcopy(ok)
    moved["approved_blobs"][PAGE] = blob_of(b"other\n")
    assert any("digest" in p for p in binding.problems(moved))
    rebound = copy.deepcopy(moved)
    rebound["binding"]["digest"] = binding.digest(rebound)          # a forger who recomputes the digest...
    assert any("approved commit holds" in p for p in binding.problems(rebound))      # ...still fails git
    g(root, "tag", "-d", "approved/P1")
    assert any("tag approved/P1" in p for p in binding.problems(ok))

    # ---- the legacy exception: named, single, covers exactly one piece
    legacy = tmp_path / "legacy.json"
    glossary = {"id": "GC-GLOSS-1", "stage": "PREVIEWED", "approved_blobs": {PAGE: "a" * 40}}
    pinned = {"exceptions": [{"id": "GC-GLOSS-1", "approved_digest": binding.bytes_digest(glossary)}]}
    legacy.write_text(json.dumps(pinned), encoding="utf-8")
    assert binding.problems(glossary, legacy) == []                              # covered without a marker, bytes pinned
    # W1: the digest is REQUIRED. An entry without one (missing, empty, blank, not a string) covers nothing.
    for bad in ({"id": "GC-GLOSS-1"}, {"id": "GC-GLOSS-1", "approved_digest": ""},
                {"id": "GC-GLOSS-1", "approved_digest": "  "}, {"id": "GC-GLOSS-1", "approved_digest": None},
                {"id": "GC-GLOSS-1", "approved_digest": ["x"]}):
        legacy.write_text(json.dumps({"exceptions": [bad]}), encoding="utf-8")
        assert any("approved_digest" in p for p in binding.legacy_problems(glossary, legacy)), bad
        assert any("UNVERIFIED" in p for p in binding.problems(glossary, legacy)), bad
    legacy.write_text(json.dumps(pinned), encoding="utf-8")
    for other in ("GC-GLOSS-2", "GC-GLOSS-3", "GC-GLOSS-1-R1", "gc-gloss-1", "GC-GLOSS-1 ", "T4-L1", "TWO", ""):
        assert any("UNVERIFIED" in p for p in binding.problems({**glossary, "id": other}, legacy)), other
    # the data cannot widen it: two entries, or an id the code does not also name, is an error, not a wider cover
    legacy.write_text(json.dumps({"exceptions": [{"id": "GC-GLOSS-1", "approved_digest": "x"}, {"id": "GC-GLOSS-2"}]}),
                      encoding="utf-8")
    assert any("single" in p for p in binding.problems(glossary, legacy))
    legacy.write_text(json.dumps({"exceptions": [{"id": "GC-GLOSS-2"}]}), encoding="utf-8")
    assert any("does not allow" in p for p in binding.problems({**glossary, "id": "GC-GLOSS-2"}, legacy))
    # a byte pin in the data refuses a row under the same id with other bytes
    legacy.write_text(json.dumps(pinned), encoding="utf-8")
    assert binding.problems(glossary, legacy) == []
    assert binding.problems({**glossary, "approved_blobs": {PAGE: "b" * 40}}, legacy)

    # ---- the real data: one exception, GC-GLOSS-1, pinned to the bytes in the real queue
    real = binding.legacy_exceptions()
    assert list(real) == ["GC-GLOSS-1"] and real["GC-GLOSS-1"]["approved_digest"]
    rows = [json.loads(l) for l in (REAL_ROOT / "production_queue.jsonl").read_text(encoding="utf-8").splitlines()
            if l.strip().startswith("{")]
    real_gloss = next(r for r in rows if r["id"] == "GC-GLOSS-1")
    assert binding.problems(real_gloss) == []
    assert binding.problems({**real_gloss, "approved_blobs": {**real_gloss["approved_blobs"], PAGE: "c" * 40}})
    for r in rows:
        if r["id"] != "GC-GLOSS-1" and r.get("approved_blobs"):
            assert binding.problems(r), r["id"]        # no other racked row rides on the exception

    # ---- the 14 waiting tiles are marked unverified, in data, and refused if ever racked unbound
    tiles = binding.unverified_tiles()
    assert len(tiles) == 14 and "GC-GLOSS-1" not in tiles
    board = (REAL_ROOT / "boards" / "APPROVALS_OWED.md").read_text(encoding="utf-8")
    titled = set(re.findall(r"^### APPROVE ([\w-]+) at ", board, re.M))
    assert set(tiles) <= titled                             # each is still on the board (marked, not deleted)
    for pid in tiles:
        assert any("UNVERIFIED" in p for p in binding.problems({"id": pid, "approved_blobs": {PAGE: "d" * 40}}))


