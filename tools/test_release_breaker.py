def test_RED_published_page_drift_never_reaches_the_board(site):
    """approval_drift's docstring says a PUBLISHED piece's missing/edited file is drift; build() only checks
    pipeline rows, so it is never shown."""
    root, blob, write_queue, _ = site
    write_queue(piece(blob, stage="PUBLISHED", published="2026-10-16"))   # file not in tree
    assert "CHANGED SINCE" in pb.build(TUE)


def test_RED_a_revision_can_never_publish(site):
    """kind='revision of a published page': the old page is in the tree with other bytes, so approval_drift
    calls it drift and the revision never holds a slot; release.py's revision branch is unreachable."""
    root, blob, write_queue, blob_of = site
    (root / PAGE).parent.mkdir(parents=True)
    (root / PAGE).write_bytes(b'<h1>Glossary I</h1>\n<a href="/lessons/a/">a</a>\n')
    newb = blob_of(b'<h1>Glossary I folded</h1>\n')
    rev = {"id": "GC-GLOSS-1-R1", "order": 100, "title": "rev", "stage": "PREVIEWED", "previewed": "2026-10-13",
           "kind": "revision of a published page", "approved_blobs": {PAGE: newb}}
    write_queue(piece(blob, stage="PUBLISHED", published="2026-10-09"), rev)
    assert release.plan(TUE)["outcome"] == "PUBLISH"
