"""Independent breaker tests for release.py / production_board.py.

    py -m pytest tools/test_release_breaker.py -q -rA

A test that FAILS on the current code marks a real defect (RED). Tests marked "HELD" are attacks that did not land.
"""
import datetime as dt
import io
