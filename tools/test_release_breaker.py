# ============================================================ Q5: verify_live
class _Resp(io.BytesIO):
    pass


def test_HELD_verify_live_maps_index_paths_and_needs_exact_bytes(monkeypatch):
    seen = []
    data = b"<h1>x</h1>\n"
    blob = __import__("hashlib").sha1(b"blob %d\0" % len(data) + data).hexdigest()
    monkeypatch.setattr(release.urllib.request, "urlopen", lambda req, timeout: (seen.append(req.full_url), _Resp(data))[1])
    assert "match" in release.verify_live({"approved_blobs": {PAGE: blob, "index.html": blob}}, 1)
    assert seen == ["https://b4him.com/lessons/glossary-beginner/", "https://b4him.com/index.html"]
    monkeypatch.setattr(release.urllib.request, "urlopen", lambda req, timeout: _Resp(b"stale\n"))
    monkeypatch.setattr(release.time, "sleep", lambda s: None)
    t = iter(range(0, 10**6, 400))
    monkeypatch.setattr(release.time, "time", lambda: next(t))
    with pytest.raises(release.ReleaseError):
        release.verify_live({"approved_blobs": {PAGE: blob}}, 1)


def test_RED_verify_live_false_negative_on_binary_with_crlf(monkeypatch):
    data = b"\x89PNG\r\n\x1a\n\0binary"
    blob = __import__("hashlib").sha1(b"blob %d\0" % len(data) + data).hexdigest()
    monkeypatch.setattr(release.urllib.request, "urlopen", lambda req, timeout: _Resp(data))
    monkeypatch.setattr(release.time, "sleep", lambda s: None)
    t = iter(range(0, 10**6, 400))
    monkeypatch.setattr(release.time, "time", lambda: next(t))
    assert "match" in release.verify_live({"approved_blobs": {"img/a.png": blob}}, 1)


