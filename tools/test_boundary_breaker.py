def test_DEFECT_registry_lets_a_child_surname_through_behind_an_html_entity(reg):
    """`&nbsp;` between a first and last name is ordinary HTML typography (keeps a name on one line). The checker
    strips tags but does not decode entities, so the surname is never seen next to the first name."""
    r = pr.check_text("<p>Peregrine&nbsp;Farquharson helped.</p>", piece_yes={"CHILD-1"}, registry=reg)
    assert r.findings and not r.ok, f"child surname published behind &nbsp;: ok={r.ok} findings={r.findings}"


def test_DEFECT_registry_misses_common_age_forms_next_to_a_child(reg):
    """Documented as best effort in the module; recorded here with exact forms so the hole has a size."""
    missed = []
    for t in ("Peregrine (9) helped.", "Peregrine, now 9. He helped.", "Peregrine's 9th birthday was that week.",
              "My son turns 8 next month.", "My daughter (11) helped."):
        r = pr.check_text(t, piece_yes={"CHILD-1"}, registry=reg)
