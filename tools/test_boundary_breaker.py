def test_attack_the_legacy_exception_data_cannot_be_widened(tmp_path):
    assert binding is not None, "no binding module: there is no named, single legacy exception"
    real = binding.legacy_exceptions()
    assert list(real) == ["GC-GLOSS-1"] and len(real["GC-GLOSS-1"].get("approved_digest", "")) == 64
    gloss = {"id": "GC-GLOSS-1", "stage": "PREVIEWED", "approved_blobs": {"lessons/x/index.html": "a" * 40}}

    def refused(row, path):
        try:
            return bool(binding.problems(row, path))
        except Exception:               # noqa: BLE001 - a raise is fail-closed, not a cover
            return True
    f = tmp_path / "legacy.json"
    for exceptions in ([{"id": "GC-GLOSS-1"}, {"id": "T4-L1"}],            # two entries
                       [{"id": "T4-L1"}],                                   # another id alone
                       [{"id": ["GC-GLOSS-1", "T4-L1"]}],                   # a list of ids
                       [{"id": "GC-GLOSS-1", "also": ["T4-L1"]}],           # a widening key the code never reads
                       [{"ids": ["GC-GLOSS-1", "T4-L1"]}]):
        f.write_text(json.dumps({"exceptions": exceptions}), encoding="utf-8")
        assert refused({**gloss, "id": "T4-L1"}, f), exceptions
    f.write_text(json.dumps({"exceptions": [{"id": "GC-GLOSS-1"}], "exceptions2": [{"id": "T4-L1"}]}), encoding="utf-8")
    assert refused({**gloss, "id": "T4-L1"}, f)
    # a moved digest: the real GC-GLOSS-1 row with one pinned blob changed is not the pinned bytes
    real_gloss = next(r for r in real_rows() if r["id"] == "GC-GLOSS-1")
    assert binding.problems(real_gloss) == []
    moved = copy.deepcopy(real_gloss)
    k = next(iter(moved["approved_blobs"]))
    moved["approved_blobs"][k] = hashlib.sha1(b"other").hexdigest()
    assert refused(moved, None)
    moved = copy.deepcopy(real_gloss)
    moved["approved_blobs"]["lessons/extra/index.html"] = "b" * 40          # one more file smuggled under the id
    assert refused(moved, None)
    moved = copy.deepcopy(real_gloss)
    moved["approved_index_entry"] = "c" * 40
    assert refused(moved, None)


