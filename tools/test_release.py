"""Tests for release.py: the actuator publishes exactly the approved bytes on their slot, and nothing else.

    py -m pytest tools/test_release.py -q

Each test builds a throwaway git repo, so the release runs the same git commands it runs on the day.
"""
import datetime as dt
import json
import pathlib
import shutil
import subprocess
import sys

import pytest

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import production_board as pb  # noqa: E402
import release  # noqa: E402

GIT = shutil.which("git")
pytestmark = pytest.mark.skipif(not GIT, reason="git not on PATH")

TUE = dt.date(2026, 10, 20)
PAGE = "lessons/glossary-beginner/index.html"
INDEX = ("<html><body>\n  <nav>\n    <a href=\"/lessons/a/\">a</a>\n  </nav>\n"
         "<!-- b4him:track n8n (generated by tools/release.py from published queue rows; do not hand-edit) -->\n"
         "<!-- /b4him:track n8n -->\n\n  <footer></footer>\n</body></html>\n")
ENTRY = {"track": "n8n", "numeral": "I", "href": "/lessons/glossary-beginner/",
         "title": "Glossary I — Beginner Terms", "blurb": "Eighteen words."}


def g(root, *args):
    return subprocess.run([GIT, "-C", str(root), *args], capture_output=True, check=True,
                          encoding="utf-8").stdout.strip()


@pytest.fixture
def site(tmp_path, monkeypatch):
    root = tmp_path / "site"
    (root / "tools" / "tracks").mkdir(parents=True)
    (root / "lessons" / "a").mkdir(parents=True)
    shutil.copy(HERE / "tracks" / "n8n.html", root / "tools" / "tracks" / "n8n.html")
    (root / "lessons" / "a" / "index.html").write_text("<p>a</p>\n", encoding="utf-8")
    (root / "lessons" / "index.html").write_text(INDEX, encoding="utf-8", newline="\n")
    (root / ".gitignore").write_text("release_log.jsonl\n__pycache__/\n", encoding="utf-8")
    g(tmp_path, "init", "-q", "-b", "main", str(root))
    g(root, "config", "user.email", "t@example.invalid")
    g(root, "config", "user.name", "test")
    g(root, "config", "core.autocrlf", "false")
    # the approved page: in the object store, NOT in the tree (racked)
    page_src = tmp_path / "approved.html"
    page_src.write_bytes(b'<h1>Glossary I</h1>\n<a href="/lessons/a/">a</a>\n')
    blob = g(root, "hash-object", "-w", str(page_src))
    monkeypatch.setattr(pb, "REPO", root)
    monkeypatch.setattr(pb, "QUEUE", root / "production_queue.jsonl")
    monkeypatch.setattr(pb, "BOARD", root / "PRODUCTION_BOARD.md")

    def write_queue(*rows, comment="# the queue\n"):
        pb.QUEUE.write_text(comment + "\n".join(json.dumps(r) for r in rows) + "\n", encoding="utf-8", newline="\n")
        g(root, "add", "-A")
        g(root, "commit", "-q", "-m", "queue")
    return root, blob, write_queue


def piece(blob, **kw):
    furn = "tools/tracks/n8n.html"
    blobs = {PAGE: blob, furn: pb.blob_sha(pb.REPO / furn)}
    base = {"id": "GC-GLOSS-1", "order": 1, "title": "Glossary I", "stage": "PREVIEWED",
            "previewed": "2026-10-13", "approved_blobs": blobs, "index_entry": ENTRY,
            "approved_index_entry": pb.entry_sha(ENTRY)}
    return {**base, **kw}


def test_an_unpinned_index_entry_refuses(site):
    root, blob, write_queue = site
    write_queue(piece(blob, approved_index_entry=None))
    d = release.plan(TUE)
    assert d["outcome"] == "FAIL" and "index_entry" in d["why"]


def test_an_entry_edited_after_approval_refuses(site):
    root, blob, write_queue = site
    write_queue(piece(blob, index_entry={**ENTRY, "blurb": "words nobody approved"}))
    assert release.plan(TUE)["outcome"] == "FAIL"


def test_a_racked_piece_is_eligible_before_its_file_exists(site):
    root, blob, write_queue = site
    write_queue(piece(blob))
    assert not (root / PAGE).exists()
    assert release.plan(TUE)["outcome"] == "PUBLISH"
    assert "| **2026-10-20** Tue | Glossary I |" in pb.build(dt.date(2026, 10, 13))


def test_release_writes_the_approved_bytes_marks_published_fills_the_index_and_commits(site):
    root, blob, write_queue = site
    other = {"id": "OTHER", "order": 2, "title": "o", "stage": "SOURCE"}
    write_queue(piece(blob), other)
    before = pb.QUEUE.read_text(encoding="utf-8").splitlines()
    commit = release.apply(TUE, release.plan(TUE), push=False)

    assert pb.blob_sha(root / PAGE) == blob
    after = pb.QUEUE.read_text(encoding="utf-8").splitlines()
    assert [a == b for a, b in zip(before, after)] == [True, False, True]      # only the piece's line changed
    row = json.loads(after[1])
    assert (row["stage"], row["published"]) == ("PUBLISHED", "2026-10-20")
    index = (root / "lessons" / "index.html").read_text(encoding="utf-8")
    assert '<a class="mod" href="/lessons/glossary-beginner/">' in index and "The n8n track" in index
    assert g(root, "rev-parse", "HEAD") == commit
    assert g(root, "status", "--porcelain") == ""
    assert g(root, "log", "-1", "--format=%s").startswith("PUBLISHED GC-GLOSS-1")


def test_an_empty_track_renders_nothing(site):
    root, blob, write_queue = site
    write_queue(piece(blob))
    assert release.render_tracks(INDEX, pb.load_queue()) == INDEX


def test_a_page_edited_after_approval_never_publishes(site):
    root, blob, write_queue = site
    write_queue(piece(blob))
    (root / PAGE).parent.mkdir(parents=True)
    (root / PAGE).write_bytes(b"<h1>edited</h1>\n")
    assert release.plan(TUE)["outcome"] == "SKIP"


def test_the_cap_holds_two_in_seven_days(site):
    root, blob, write_queue = site
    pubs = [{"id": f"P{i}", "order": 9, "title": "p", "stage": "PUBLISHED", "published": d}
            for i, d in enumerate(["2026-10-14", "2026-10-16"])]
    write_queue(piece(blob), *pubs)
    d = release.plan(TUE)
    assert d["outcome"] == "SKIP" and "cap" in d["why"]


def test_not_a_release_day(site):
    root, blob, write_queue = site
    write_queue(piece(blob))
    assert release.plan(dt.date(2026, 10, 21))["outcome"] == "SKIP"


def test_a_missed_tuesday_goes_out_friday(site):
    root, blob, write_queue = site
    write_queue(piece(blob))
    assert release.plan(dt.date(2026, 10, 23))["outcome"] == "PUBLISH"


def test_a_broken_link_refuses_and_restores_the_tree(site, tmp_path):
    root, _, write_queue = site
    bad = tmp_path / "bad.html"
    bad.write_bytes(b'<a href="/lessons/nowhere/">x</a>\n')
    blob = g(root, "hash-object", "-w", str(bad))
    write_queue(piece(blob))
    head = g(root, "rev-parse", "HEAD")
    with pytest.raises(release.ReleaseError, match="404"):
        release.apply(TUE, release.plan(TUE), push=False)
    assert g(root, "rev-parse", "HEAD") == head
    assert g(root, "status", "--porcelain") == ""
    assert not (root / PAGE).exists()


def test_a_dirty_tree_refuses(site):
    root, blob, write_queue = site
    write_queue(piece(blob))
    (root / "stray.txt").write_text("someone else's work\n", encoding="utf-8")
    with pytest.raises(release.ReleaseError, match="not clean"):
        release.apply(TUE, release.plan(TUE), push=False)
    assert (root / "stray.txt").exists()


def test_a_piece_without_pinned_bytes_fails_loudly(site):
    root, blob, write_queue = site
    write_queue(piece(blob, approved_blobs=None))
    assert release.plan(TUE)["outcome"] == "FAIL"


def _origin(root, tmp_path):
    bare = tmp_path / "origin.git"
    g(tmp_path, "init", "-q", "--bare", "-b", "main", str(bare))
    g(root, "remote", "add", "origin", str(bare))
    g(root, "push", "-q", "origin", "main")
    return bare


def test_unpushed_bookkeeping_from_approvals_may_ride_out_with_a_release(site, tmp_path):
    root, blob, write_queue = site
    write_queue(piece(blob))
    _origin(root, tmp_path)
    (root / "boards").mkdir()
    (root / "boards" / "APPROVALS_OWED.md").write_text("# board\n", encoding="utf-8")
    g(root, "add", "boards/APPROVALS_OWED.md")
    g(root, "commit", "-q", "-m", "Offer X at abc1234 for Daniel's one-tap approval")
    assert release.preflight(TUE) == []


def test_a_page_commit_cannot_ride_out_by_naming_itself_like_bookkeeping(site, tmp_path):
    root, blob, write_queue = site
    write_queue(piece(blob))
    _origin(root, tmp_path)
    (root / "lessons" / "a" / "index.html").write_text("<p>changed, never approved</p>\n", encoding="utf-8")
    g(root, "commit", "-q", "-am", "APPROVED X at abc1234: Daniel's tap")
    with pytest.raises(release.ReleaseError, match="unapproved"):
        release.preflight(TUE)


def test_apply_refuses_any_day_but_today(site, capsys):
    root, blob, write_queue = site
    write_queue(piece(blob))
    assert release.main(["--apply", "--date", "2020-01-07"]) == 1
    assert "today" in capsys.readouterr().out
