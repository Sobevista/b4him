def test_publishes_only_pinned_bytes(site):
    """The release commit carries the pinned page byte-for-byte and touches nothing but the queue line, the
    generated index and the board; the index's track block is exactly the pinned furniture around the pinned entry."""
    root, blob, write_queue, _, _ = site
    write_queue(piece(blob), {"id": "OTHER", "order": 2, "title": "o", "stage": "SOURCE"})
    before = g(root, "rev-parse", "HEAD")
    commit = release.apply(TUE, release.plan(TUE))
    assert g(root, "rev-parse", f"{commit}^") == before
    changed = set(g(root, "diff-tree", "--no-commit-id", "--name-only", "-r", commit).split())
    assert changed == {PAGE} | BOOKKEEPING_AND_RELEASE, changed
    assert g(root, "rev-parse", f"{commit}:{PAGE}") == blob
    assert g(root, "rev-parse", f"{commit}:{FURN}") == piece(blob)["approved_blobs"][FURN]
    expected_block = (root / FURN).read_text(encoding="utf-8").replace(
        "{{entries}}", release.ENTRY.format(**ENTRY)).lstrip("\n")
    index = (root / "lessons" / "index.html").read_text(encoding="utf-8")
    assert expected_block in index
    assert index.count('class="mod"') == 1


