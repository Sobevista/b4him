    write_queue(piece(blob))
    with_origin(root, tmp_path)
    real = release.git

    def broken_network(*a, **k):
        if a[:1] == ("push",):
            raise OSError("network down")
        return real(*a, **k)
    monkeypatch.setattr(release, "git", broken_network)
    monkeypatch.setattr(release.dt, "date", FakeDate)
    try:
        code = release.main(["--apply", "--push"])
    except Exception:                                      # noqa: BLE001 - a crash is the defect
        code = "crashed"
    assert code == 1
    last = log_lines(root)[-1]
    assert last["outcome"] == "FAIL" and "OSError" in last["why"] and "on local main" in last["why"], last
    tile = (root / "release_alarm.md").read_text(encoding="utf-8")
    assert "### Release run failed 2026-10-20" in tile and "**DANIEL:** _pending_" in tile
    assert g(root, "status", "--porcelain") == ""          # the tile is ignored; the release commit stands


