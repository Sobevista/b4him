def g(root, *args):
    return subprocess.run([GIT, "-C", str(root), *args], capture_output=True, check=True,
                          encoding="utf-8").stdout.strip()


def commit_all(root, msg="x"):
    g(root, "add", "-A")
    g(root, "commit", "-q", "-m", msg)


def log_lines(root):
    p = root / "release_log.jsonl"
    return [json.loads(l) for l in p.read_text(encoding="utf-8").splitlines()] if p.exists() else []


def with_origin(root, tmp_path):
    bare = tmp_path / "origin.git"
    g(tmp_path, "init", "-q", "--bare", "-b", "main", str(bare))
    g(root, "remote", "add", "origin", str(bare))
    g(root, "push", "-q", "origin", "main")
    return bare


def snapshot(root):
    """Every tracked and untracked byte in the tree (ignored files included), keyed by path."""
    out = {}
    for p in root.rglob("*"):
        if p.is_file() and ".git" not in p.relative_to(root).parts:
            out[p.relative_to(root).as_posix()] = p.read_bytes()
    return out


