def piece(blob, **kw):
    """A racked piece pinned the way approvals.py pins: page + the track furniture AS IT STANDS NOW + entry hash."""
    blobs = {PAGE: blob, FURN: pb.blob_sha(pb.REPO / FURN)}
    base = {"id": "GC-GLOSS-1", "order": 1, "title": "Glossary I", "stage": "PREVIEWED",
            "previewed": "2026-10-13", "approved_blobs": blobs, "index_entry": ENTRY,
            "approved_index_entry": pb.entry_sha(ENTRY)}
    return {**base, **kw}


def published(pid, page_rel, page_blob, entry, order=0, day="2026-10-09", furn=FURN):
    """A row a past release left behind: PUBLISHED, its page and furniture pinned, its entry pinned by hash."""
    return {"id": pid, "order": order, "title": pid, "stage": "PUBLISHED", "published": day,
            "approved_blobs": {page_rel: page_blob, furn: pb.blob_sha(pb.REPO / furn)},
            "index_entry": entry, "approved_index_entry": pb.entry_sha(entry)}


def racked(pid, page_rel, page_blob, order, entry=None, extra_blobs=None, **kw):
    blobs = {page_rel: page_blob, **(extra_blobs or {})}
    if entry and entry.get("track"):
        blobs.setdefault(f"tools/tracks/{entry['track']}.html", pb.blob_sha(pb.REPO / f"tools/tracks/{entry['track']}.html"))
    row = {"id": pid, "order": order, "title": pid, "stage": "PREVIEWED", "previewed": "2026-10-13",
           "approved_blobs": blobs}
    if entry:
        row.update(index_entry=entry, approved_index_entry=pb.entry_sha(entry))
    return {**row, **kw}


